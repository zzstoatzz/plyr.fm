/** Lucide-shaped props: a filled `fill` draws the solid weight and a heavy `strokeWidth` the bold one, so active states read at a glance. */
export interface IconProps { size?: number; color?: string; fill?: string; strokeWidth?: number; weight?: IconWeight; style?: PhosphorProps['style'] }
export type Icon = ComponentType<IconProps>;

function icon(Base: ComponentType<PhosphorProps>): Icon {
  return function PlyrIcon({ size = 24, color, fill, strokeWidth, weight, style }: IconProps) {
    const chosen = weight ?? (fill && fill !== 'none' && fill !== 'transparent' ? 'fill' : (strokeWidth ?? 2) >= 2.3 ? 'bold' : 'regular');
    return <Base size={size} color={color} weight={chosen} style={style} />;
  };
}

