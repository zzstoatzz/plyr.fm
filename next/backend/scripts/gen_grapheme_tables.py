"""Generate src/internal/text/grapheme_tables.zig from the `regex` package's
Unicode property data (UAX #29 Grapheme_Cluster_Break, Extended_Pictographic,
and Indic_Conjunct_Break).

    uv run --with regex python next/backend/scripts/gen_grapheme_tables.py
"""

from __future__ import annotations

import pathlib
import unicodedata

import regex

OUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "src/internal/text/grapheme_tables.zig"
)

GCB = [
    "CR",
    "LF",
    "Control",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
]
INCB = ["Linker", "Consonant", "Extend"]

ALL = "".join(chr(c) for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF)


def ranges(pattern: str) -> list[tuple[int, int]]:
    cps = sorted(ord(m) for m in regex.findall(pattern, ALL))
    out: list[tuple[int, int]] = []
    for cp in cps:
        if out and out[-1][1] + 1 == cp:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def zig_ranges(name: str, rs: list[tuple[int, int]]) -> str:
    body = "\n".join(f"    .{{ 0x{a:X}, 0x{b:X} }}," for a, b in rs)
    return f"pub const {name} = [_][2]u21{{\n{body}\n}};\n"


def snake(name: str) -> str:
    return regex.sub(r"(?<=[a-z])(?=[A-Z])", "_", name).lower()


def main() -> None:
    parts = [
        "//! Generated by scripts/gen_grapheme_tables.py. Do not edit.\n",
        f"//! regex {regex.__version__}; python unicodedata {unicodedata.unidata_version}.\n\n",
    ]
    for name in GCB:
        parts.append(
            zig_ranges(
                f"gcb_{snake(name)}", ranges(rf"\p{{Grapheme_Cluster_Break={name}}}")
            )
        )
    parts.append(
        zig_ranges("extended_pictographic", ranges(r"\p{Extended_Pictographic}"))
    )
    for name in INCB:
        parts.append(
            zig_ranges(
                f"incb_{name.lower()}", ranges(rf"\p{{Indic_Conjunct_Break={name}}}")
            )
        )
    OUT.write_text("".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
